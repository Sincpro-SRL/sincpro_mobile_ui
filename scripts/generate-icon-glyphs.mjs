// Regenerates sincpro_mobile_ui/Display/icon-glyphs.ts from the Material Symbols
// codepoints shipped by expo-symbols. Run with: node scripts/generate-icon-glyphs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const require = createRequire(path.join(root, "package.json"));
const codepoints = JSON.parse(
  readFileSync(
    path.join(
      path.dirname(require.resolve("expo-symbols/package.json")),
      "build/android/symbols.json",
    ),
    "utf8",
  ),
);
const iconMap = readFileSync(
  path.join(root, "sincpro_mobile_ui/Display/icon-map.ts"),
  "utf8",
);
const entries = [
  ...iconMap.matchAll(/^\s+"?([\w-]+)"?: \{ sf: "[^"]+", md: "([^"]+)" \},$/gm),
];
const lines = entries.map(([, name, md]) => {
  const code = codepoints[md];
  if (typeof code !== "number") throw new Error(`No Material Symbols codepoint for ${md}`);
  const key = /^[a-z]+$/.test(name) ? name : `"${name}"`;
  return `  ${key}: 0x${code.toString(16)},`;
});
const source = `import type { BuiltInIconName } from "@sincpro/mobile-ui/Display/icon-map";

// Generated by scripts/generate-icon-glyphs.mjs from expo-symbols' Material Symbols table.
export const MATERIAL_CODEPOINTS: Readonly<Record<BuiltInIconName, number>> = {
${lines.join("\n")}
};
`;
writeFileSync(path.join(root, "sincpro_mobile_ui/Display/icon-glyphs.ts"), source);
console.log(`icon-glyphs.ts: ${lines.length} glyphs`);
